/**
 * What a tier actually sends to the model, as readable markdown: server instructions and every
 * model-visible tool's description, with the 4,096-char cut of Claude Code 2.1.296+ (a tool sent up
 * front) and Cowork marked (CC, HD), plus the input parameters. Claude Code cuts a description loaded
 * through tool search at 16,384, past every tier here. The evals ran on a Claude Code that cut at
 * 2,048 (Q7); set CLAUDE_CODE_MAX_MCP_DESCRIPTION_LENGTH=2048 to reproduce that.
 * The output schema is listed by size only, because the model never receives it (Q11).
 *
 * Generated from the live server factory, never written by hand: `npm run wire-view` rewrites
 * docs/wire/, and src/wire-view.test.ts fails when a file there no longer matches.
 */
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { createServer, type ServerVariant } from './server.js';
import type { BagClientLike, EpOnlineClientLike } from './tools/get-building-profile.js';

/**
 * Claude Code 2.1.296+ for a tool sent up front and for server instructions (CC, 2026-10-26), and
 * Cowork (HD, 2026-09-27). claude.ai chat, ChatGPT and Codex deliver the whole description.
 */
export const CUT = 4096;
export const WIRE_VIEW_ARMS: { arm: ServerVariant; blurb: string }[] = [
  {
    arm: 'best',
    blurb:
      'The reference implementation: everything before the call fits inside the cut; meaning travels in field names and the response.',
  },
  {
    arm: 'rich',
    blurb:
      'The older, description-heavy tier: half its description sits past the cut, and the evals ran on a Claude Code that cut it at 2,048.',
  },
  { arm: 'minimal', blurb: 'The thin wrapper: same data, one-line descriptions, no guidance.' },
];
/** App-only tools (`_meta.ui.visibility: ['app']`) are called by the UI, never shown to the model. */
const modelVisible = (t: { _meta?: unknown }) =>
  !(t._meta as { ui?: { visibility?: string[] } } | undefined)?.ui?.visibility?.every((v) => v === 'app');

const noBag: BagClientLike = {
  findAddress: async () => [],
  getVerblijfsobject: async () => null,
  getPand: async () => null,
};
const noEp: EpOnlineClientLike = { getByBagVboId: async () => [] };

const fence = (text: string) => '````text\n' + text + '\n````';

/** The text as delivered, with a visible marker where Claude Code and Cowork stop sending it. */
export function markCut(text: string): string {
  if (text.length <= CUT) return fence(text);
  const lost = text.length - CUT;
  return (
    fence(text.slice(0, CUT)) +
    `\n\n> ✂ **Claude Code (a tool sent up front) and Cowork cut here, at character ${CUT.toLocaleString('en')}.** ` +
    `They never send the ${lost.toLocaleString('en')} characters below (${Math.round((100 * lost) / text.length)}%).\n\n` +
    '<details><summary>Not delivered on Claude Code or Cowork</summary>\n\n' +
    fence(text.slice(CUT)) +
    '\n\n</details>'
  );
}

/** Codex and ChatGPT Work drop every parameter describe once the serialized input schema passes 5,000 chars (HD). */
const SCHEMA_CUT = 5000;
const schemaNote = (chars: number) =>
  `${chars.toLocaleString('en')} chars serialized. ` +
  (chars > SCHEMA_CUT
    ? `Over ${SCHEMA_CUT.toLocaleString('en')}: Codex and ChatGPT Work drop every description below (HD).`
    : `Under ${SCHEMA_CUT.toLocaleString('en')}, so every measured client receives the descriptions below (HD).`);

type Prop = { type?: string; description?: string; enum?: unknown[] };

export async function renderWireView(arm: ServerVariant, blurb: string): Promise<string> {
  const server = createServer({ variant: arm, bagClient: noBag, epOnlineClient: noEp });
  const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
  const client = new Client({ name: 'wire-view', version: '0.0.0' });
  await Promise.all([client.connect(clientTransport), server.connect(serverTransport)]);
  const { tools } = await client.listTools();
  const instructions = client.getInstructions() ?? '';
  await client.close();

  const out: string[] = [
    `# \`${arm}\` — what the model receives`,
    '',
    `${blurb}`,
    '',
    `Generated by \`npm run wire-view\` from \`createServer({ variant: '${arm}' })\`. Do not edit by hand.`,
    '',
    `## Server instructions (${instructions.length.toLocaleString('en')} chars)`,
    '',
    instructions ? markCut(instructions) : '_none_',
  ];
  for (const tool of tools.filter(modelVisible)) {
    const name = tool.name;
    const description = tool.description ?? '';
    const props = ((tool.inputSchema as { properties?: Record<string, Prop> }).properties ?? {}) as Record<
      string,
      Prop
    >;
    const required = new Set((tool.inputSchema as { required?: string[] }).required ?? []);
    out.push(
      '',
      `## \`${name}\``,
      '',
      `### Description (${description.length.toLocaleString('en')} chars)`,
      '',
      markCut(description),
      '',
      '### Input parameters (delivered)',
      '',
      schemaNote(JSON.stringify(tool.inputSchema).length),
      '',
      '| parameter | type | description |',
      '|---|---|---|',
      ...Object.entries(props).map(
        ([k, p]) =>
          `| \`${k}\`${required.has(k) ? ' *' : ''} | ${p.enum ? p.enum.map((v) => `\`${String(v)}\``).join(' · ') : (p.type ?? '')} | ${(p.description ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')} |`,
      ),
      '',
      '### Output schema (not delivered on Claude hosts)',
      '',
      tool.outputSchema
        ? `${JSON.stringify(tool.outputSchema).length.toLocaleString('en')} chars, ${Object.keys((tool.outputSchema as { properties?: object }).properties ?? {}).length} top-level fields. Claude Code, Cowork and claude.ai chat do not pass it to the model (Q11, HD); Codex and ChatGPT Work do. Nothing only in it can carry meaning.`
        : '_none_',
    );
  }
  return out.join('\n') + '\n';
}
